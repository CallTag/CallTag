    fun detect(phone: String): String {
        val number = phone.trim()
        if (number in setOf("110", "112", "113", "115", "117", "118", "119", "129", "14080")) return "Layanan Darurat Nasional Indonesia"
        if (number.length == 7 && number.startsWith("150")) return "Layanan Nasional Indonesia"
        if (!number.startsWith("+") || number.drop(1).any { it !in '0'..'9' }) return "Konteks nomor tidak diketahui"
        if (number.startsWith("+62") && number.length > 3) {
            mobile.entries.firstOrNull { number.length > it.key.length && number.startsWith(it.key) }?.let { return it.value }
            val national = number.drop(3)
            for (length in 3 downTo 2) {
                if (national.length > length) areas[national.take(length)]?.let { return "PSTN Indonesia ($it)" }
            }
            return "Operator Telekomunikasi Indonesia"
        }
        for (length in 3 downTo 1) {
            if (number.length > length + 1) countries[number.drop(1).take(length)]?.let {
                return "Nomor internasional — $it; waspadai panggilan tak dikenal, kode negara bukan bukti spam"
            }
        }
        return "Konteks nomor internasional tidak diketahui; kode negara bukan bukti spam"
    }
